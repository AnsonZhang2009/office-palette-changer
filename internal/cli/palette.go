// multiFlag collects a repeatable (or comma-separated) string flag.
type multiFlag []string

func (m *multiFlag) String() string { return strings.Join(*m, ",") }
func (m *multiFlag) Set(v string) error {
	for _, part := range strings.Split(v, ",") {
		if p := strings.TrimSpace(part); p != "" {
			*m = append(*m, p)
		}
	}
	return nil
}

type paletteFlags struct {
	interactive bool
	text, bg    string
	accents     multiFlag
	dark        bool
	headingFont string
	bodyFont    string
	noHeadings  bool
	print       bool
	here        bool
	force       bool
}

func cmdPalette(args []string) int {
	fs := newFlagSet("palette",
		"ostyle palette <name> <color...> [--text hex] [--background hex] [--accent hex]... [--dark] [--print]\n"+
			"       ostyle palette -i    (guided wizard)")
	var pf paletteFlags
	fs.BoolVar(&pf.interactive, "i", false, "guided wizard: prompts for colors and previews the result")
	fs.BoolVar(&pf.interactive, "interactive", false, "same as -i")
	fs.StringVar(&pf.text, "text", "", "force the text color (dk1)")
	fs.StringVar(&pf.bg, "background", "", "force the background color (lt1)")
	fs.Var(&pf.accents, "accent", "explicit accent color, in order (repeatable or comma-separated)")
	fs.BoolVar(&pf.dark, "dark", false, "dark palette: light text on a dark canvas (Word stays dark-on-white)")
	fs.StringVar(&pf.headingFont, "heading-font", "", "heading (major) font")
	fs.StringVar(&pf.bodyFont, "body-font", "", "body (minor) font")
	fs.BoolVar(&pf.noHeadings, "no-headings", false, "omit the default @word heading styles")
	fs.BoolVar(&pf.print, "print", false, "print the theme CSS to stdout instead of writing a file")
	fs.BoolVar(&pf.here, "here", false, "write into the current directory instead of the theme dir")
	fs.BoolVar(&pf.force, "force", false, "overwrite an existing theme file")
	if err := parseMixed(fs, args); err != nil {
		return 2
	}

	if pf.interactive {
		return runPaletteWizard(bufio.NewReader(os.Stdin), &pf)
	}
	pos := fs.Args()
	if len(pos) < 1 {
		fs.Usage()
		fmt.Fprintln(os.Stderr, "\ntip: `ostyle palette -i` walks you through it")
		return 2
	}
	name := pos[0]
	if err := validThemeName(name); err != nil {
		return fail("%v", err)
	}
	colors := pos[1:]
	if len(colors) == 0 && pf.text == "" && pf.bg == "" && len(pf.accents) == 0 {
		return fail("give at least one color, e.g. ostyle palette %s \"#0B3954\" \"#FF5A5F\"", name)
	}

	res, err := palette.Generate(colors, palette.Options{
		Text: pf.text, Background: pf.bg, Accents: pf.accents, Dark: pf.dark,
	})
	if err != nil {
		return fail("%v", err)
	}
	t := buildPaletteTheme(name, res, &pf, paletteSourceLine(name, colors, &pf))
	printPaletteResult(res)
	for _, w := range res.Warnings {
		fmt.Fprintf(os.Stderr, "warning: %s\n", w)
	}
	if pf.print {
		fmt.Print(t.ToCSS())
		return 0
	}
	return writeGeneratedTheme(t, name, pf.here, pf.force)
}

func validThemeName(name string) error {
	if name == "" || strings.ContainsAny(name, "/\\") || strings.Contains(name, ".") || strings.HasPrefix(name, "-") {
		return fmt.Errorf("theme name must be a plain name like \"ocean\" (got %q)", name)
	}
	return nil
}

// buildPaletteTheme turns a generated palette into a full Theme, adding
// default heading styles and the dark-mode Word/PowerPoint overrides.
func buildPaletteTheme(name string, res *palette.Result, pf *paletteFlags, source string) *theme.Theme {
	colors := map[string]string{}
	for k, v := range res.Palette.Colors {
		colors[k] = v
	}
	t := &theme.Theme{
		Name:         name,
		Source:       source,
		Base:         theme.Palette{Colors: colors, MajorFont: pf.headingFont, MinorFont: pf.bodyFont},
		WordHeadings: map[int]*theme.HeadingStyle{},
	}
	if res.Dark {
		t.Word = theme.Palette{Colors: map[string]string{}}
		for k, v := range res.WordOverrides {
			t.Word.Colors[k] = v
		}
		t.PPTBackground = "scheme:lt1"
	}
	if !pf.noHeadings {
		word := t.ForWord()
		pt := func(v float64) *float64 { return &v }
		yes := true
		t.WordHeadings[1] = &theme.HeadingStyle{SizePt: pt(20), Bold: &yes, Color: word.Colors["accent1"], SpaceBeforePt: pt(18), SpaceAfterPt: pt(6)}
		t.WordHeadings[2] = &theme.HeadingStyle{SizePt: pt(15), Bold: &yes, Color: word.Colors["dk2"], SpaceBeforePt: pt(14)}
		t.WordHeadings[3] = &theme.HeadingStyle{SizePt: pt(12.5), Bold: &yes, Color: word.Colors["accent2"], SpaceBeforePt: pt(12)}
	}
	return t
}

// paletteSourceLine reconstructs an equivalent command line for the theme's
// "generated by" header.
func paletteSourceLine(name string, colors []string, pf *paletteFlags) string {
	parts := []string{"ostyle palette", name}
	for _, c := range colors {
		parts = append(parts, quoteArg(c))
	}
	if pf.text != "" {
		parts = append(parts, "--text", quoteArg(pf.text))
	}
	if pf.bg != "" {
		parts = append(parts, "--background", quoteArg(pf.bg))
	}
	for _, a := range pf.accents {
		parts = append(parts, "--accent", quoteArg(a))
	}
	if pf.dark {
		parts = append(parts, "--dark")
	}
	if pf.headingFont != "" {
		parts = append(parts, "--heading-font", quoteArg(pf.headingFont))
	}
	if pf.bodyFont != "" {
		parts = append(parts, "--body-font", quoteArg(pf.bodyFont))
	}
	if pf.noHeadings {
		parts = append(parts, "--no-headings")
	}
	return strings.Join(parts, " ")
}

func quoteArg(s string) string {
	if strings.ContainsAny(s, " #\"'") {
		return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
	}
	return s
}

func printPaletteResult(res *palette.Result) {
	fmt.Println("Generated palette:")
	for _, k := range theme.ColorKeys {
		s := res.Slots[k]
		detail := s.Origin
		if s.Note != "" && s.Note != s.Origin {
			detail = s.Origin + ": " + s.Note
		}
		fmt.Printf("  %s  (%s)\n", swatch(s.Hex, slotLabels[k]), detail)
	}
	if res.Dark {
		fmt.Println("  dark palette: PowerPoint gets the dark canvas; Word keeps dark-on-white text via @word overrides")
	}
	fmt.Println()
}

func themeTargetPath(name string, here bool) string {
	if here {
		return name + ".css"
	}
	return filepath.Join(UserThemeDir(), name+".css")
}

func writeGeneratedTheme(t *theme.Theme, name string, here, force bool) int {
	path := themeTargetPath(name, here)
	if err := writeThemeFile(path, t.ToCSS(), force); err != nil {
		return fail("%v", err)
	}
	fmt.Printf("created %s\n", path)
	fmt.Printf("apply with:  ostyle apply %s <file.docx|file.pptx>   or   ostyle apply %s --active --app word|powerpoint\n", name, name)
	return 0
}

// writeThemeFile creates the theme directory on demand and refuses to
// clobber an existing file unless force is set.
func writeThemeFile(path, content string, force bool) error {
	if _, err := os.Stat(path); err == nil && !force {
		return fmt.Errorf("%s already exists (use --force to overwrite)", path)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("creating theme dir: %w", err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		return fmt.Errorf("writing theme: %w", err)
	}
	return nil
}

// ---- interactive wizard ----------------------------------------------------

type prompter struct {
	in  *bufio.Reader
	eof bool
}

func (p *prompter) ask(prompt string) string {
	if p.eof {
		return ""
	}
	fmt.Print(prompt)
	line, err := p.in.ReadString('\n')
	if err != nil {
		if err == io.EOF && line != "" {
			return strings.TrimSpace(line)
		}
		p.eof = true
		fmt.Println()
		return ""
	}
	return strings.TrimSpace(line)
}

// askColor loops until it gets a valid hex color or a blank line.
func (p *prompter) askColor(prompt string) string {
	for !p.eof {
		s := p.ask(prompt)
		if s == "" {
			return ""
		}
		if norm, err := theme.NormalizeHex(s); err == nil {
			return "#" + norm
		}
		fmt.Println("  not a hex color (e.g. #1A2B3C) — try again, or leave blank")
	}
	return ""
}

func (p *prompter) yesNo(prompt string, def bool) bool {
	s := strings.ToLower(p.ask(prompt))
	switch s {
	case "y", "yes":
		return true
	case "n", "no":
		return false
	}
	return def
}

func runPaletteWizard(in *bufio.Reader, pf *paletteFlags) int {
	p := &prompter{in: in}
	fmt.Println("ostyle palette wizard — blank answers mean \"auto\". Ctrl-D aborts.")
	fmt.Println()

	var name string
	for {
		name = p.ask("Theme name: ")
		if p.eof {
			return abortWizard()
		}
		if err := validThemeName(name); err == nil {
			break
		}
		fmt.Println("  use a plain name like \"ocean\"")
	}

	text := p.askColor("Text color (blank = auto): ")
	bg := p.askColor("Background color (blank = auto): ")
	fmt.Println("Accent colors — one per line, blank line to finish:")
	var accents []string
	for !p.eof {
		c := p.askColor("> ")
		if c == "" {
			if len(accents) == 0 && text == "" && bg == "" {
				fmt.Println("  give at least one color")
				continue
			}
			break
		}
		accents = append(accents, c)
		if colorEnabled() {
			fmt.Printf("  %s %s\n", swatchInline(strings.TrimPrefix(c, "#")), c)
		}
		if len(accents) == 6 {
			fmt.Println("  that's the maximum of 6 accents")
			break
		}
	}
	if p.eof {
		return abortWizard()
	}
	dark := p.yesNo("Dark theme? [y/N] ", pf.dark)
	headingFont := p.ask("Heading font (blank = keep the document's): ")
	bodyFont := p.ask("Body font (blank = keep the document's): ")
	if p.eof {
		return abortWizard()
	}

	flags := paletteFlags{text: text, bg: bg, dark: dark, headingFont: headingFont, bodyFont: bodyFont,
		noHeadings: pf.noHeadings, here: pf.here, force: pf.force}
	res, err := palette.Generate(accents, palette.Options{Text: text, Background: bg, Dark: dark})
	if err != nil {
		return fail("%v", err)
	}
	fmt.Println()
	printPaletteResult(res)
	for _, w := range res.Warnings {
		fmt.Printf("warning: %s\n", w)
	}
	t := buildPaletteTheme(name, res, &flags, paletteSourceLine(name, accents, &flags))

	path := themeTargetPath(name, pf.here)
	switch strings.ToLower(p.ask(fmt.Sprintf("Write %s? [Y]es / [p]rint only / [n]o: ", path))) {
	case "", "y", "yes":
		return writeGeneratedTheme(t, name, pf.here, pf.force)
	case "p", "print":
		fmt.Print(t.ToCSS())
		return 0
	default:
		fmt.Println("not written")
		return 0
	}
}

func abortWizard() int {
	fmt.Fprintln(os.Stderr, "ostyle: aborted")
	return 1
}
